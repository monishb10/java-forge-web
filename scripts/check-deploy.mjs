import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {createRequire} from 'node:module';
const root=path.resolve(import.meta.dirname,'..');
assert.ok(fs.existsSync(root+'/scripts/configure-deploy.mjs'),'Deployment must validate its database and public account URL');
const {deploymentConfig}=await import('./configure-deploy.mjs');
const values={APP_URL:'https://java-forge.example.test',D1_DATABASE_ID:'12345678-abcd-4321-abcd-123456789012',OAUTH_CLIENT_ID:'oauth-fixture'};
assert.throws(()=>deploymentConfig({}),/APP_URL/);
assert.throws(()=>deploymentConfig({...values,APP_URL:'http://example.test'}),/HTTPS/);
assert.throws(()=>deploymentConfig({...values,APP_URL:'https://example.test/subpath'}),/origin/);
assert.throws(()=>deploymentConfig({...values,D1_DATABASE_ID:'00000000-0000-4000-8000-000000000000'}),/database/);
assert.throws(()=>deploymentConfig({...values,D1_DATABASE_ID:'not-a-database'}),/database/);
assert.throws(()=>deploymentConfig({...values,OAUTH_CLIENT_ID:''}),/OAUTH_CLIENT_ID/);
const config=deploymentConfig({...values,GITHUB_CLIENT_SECRET:'do-not-embed',TOKEN_ENCRYPTION_KEY:'secret-encryption'});
assert.equal(config.vars.APP_URL,values.APP_URL);
assert.equal(config.vars.GITHUB_CLIENT_ID,values.OAUTH_CLIENT_ID);
assert.equal(config.d1_databases[0].database_id,values.D1_DATABASE_ID);
assert.ok(!JSON.stringify(config).includes('do-not-embed')&&!JSON.stringify(config).includes('secret-encryption'));
assert.equal(deploymentConfig({},true).vars.APP_URL,'http://127.0.0.1:5173');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'java-forge-client-'));
const require=createRequire(root+'/package.json'),ts=require('typescript');
fs.writeFileSync(dir+'/session.mjs',ts.transpileModule(fs.readFileSync(root+'/lib/session-client.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText);
const {setSessionAccount,sessionHeaders}=await import(dir+'/session.mjs');
assert.deepEqual(sessionHeaders(),{});
setSessionAccount('github:101');assert.equal(sessionHeaders()['x-java-forge-account'],'github:101');
setSessionAccount('github:202');assert.equal(sessionHeaders()['x-java-forge-account'],'github:202');
setSessionAccount(null);assert.deepEqual(sessionHeaders(),{});
fs.rmSync(dir,{recursive:true,force:true});
console.log('15 deployment configuration and browser-account checks passed.');
